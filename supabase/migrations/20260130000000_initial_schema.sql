-- ---------------------------------------------------------------------
-- Profiles (1:1 with auth.users)
-- ---------------------------------------------------------------------

create table public.profiles (
    id uuid primary key references auth.users (id) on delete cascade,
    email text not null,
    full_name text,
    avatar_url text,
    bio text,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

create index profiles_email_idx on public.profiles using btree (email);

create or replace function public.update_updated_at_column()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create trigger update_profiles_updated_at
    before update on public.profiles
    for each row execute function public.update_updated_at_column();

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
    insert into public.profiles (id, email, full_name)
    values (
        new.id,
        new.email,
        coalesce(new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'name', '')
    );
    return new;
end;
$$;

create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;

create policy "Users can view own profile" on public.profiles
    for select using (auth.uid() = id);
create policy "Enable insert for authenticated users" on public.profiles
    for insert with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles
    for update using (auth.uid() = id);

-- ---------------------------------------------------------------------
-- Portfolios
-- ---------------------------------------------------------------------

create table public.portfolios (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users (id),
    name text not null,
    created_at timestamptz not null default timezone('utc'::text, now()),
    slug text not null default substr(md5(random()::text), 1, 12),
    market text not null default 'BIST',
    constraint portfolios_slug_unique unique (slug),
    constraint portfolios_market_check check (market = 'BIST')
);

create index portfolios_slug_idx on public.portfolios using btree (slug);

alter table public.portfolios enable row level security;

create policy "Users can view own portfolios" on public.portfolios
    for select using (auth.uid() = user_id);
create policy "Users can create own portfolios" on public.portfolios
    for insert with check (auth.uid() = user_id);
create policy "Users can update own portfolios" on public.portfolios
    for update using (auth.uid() = user_id);
create policy "Users can delete own portfolios" on public.portfolios
    for delete using (auth.uid() = user_id);

-- ---------------------------------------------------------------------
-- Transactions
-- quantity/price are as entered; adjusted_* are restated for later stock
-- splits by the backend (see backend/app/services/portfolio_service.py).
-- ---------------------------------------------------------------------

create table public.transactions (
    id bigint generated by default as identity primary key,
    portfolio_id bigint not null references public.portfolios (id) on delete cascade,
    ticker text not null,
    operation text not null,
    quantity numeric not null,
    price numeric not null,
    date date not null,
    created_at timestamptz not null default timezone('utc'::text, now()),
    adjusted_price numeric not null,
    adjusted_quantity numeric not null
);

alter table public.transactions enable row level security;

create policy "Users can view own transactions" on public.transactions
    for select using (exists (
        select 1 from public.portfolios
        where portfolios.id = transactions.portfolio_id
          and portfolios.user_id = auth.uid()
    ));
create policy "Users can create own transactions" on public.transactions
    for insert with check (exists (
        select 1 from public.portfolios
        where portfolios.id = transactions.portfolio_id
          and portfolios.user_id = auth.uid()
    ));
create policy "Users can update own transactions" on public.transactions
    for update using (exists (
        select 1 from public.portfolios
        where portfolios.id = transactions.portfolio_id
          and portfolios.user_id = auth.uid()
    ));
create policy "Users can delete own transactions" on public.transactions
    for delete using (exists (
        select 1 from public.portfolios
        where portfolios.id = transactions.portfolio_id
          and portfolios.user_id = auth.uid()
    ));

-- ---------------------------------------------------------------------
-- Market prices (shared cache, backend-only: RLS on, no policies)
-- ---------------------------------------------------------------------

create table public.market_prices (
    id bigint generated by default as identity,
    ticker text not null,
    date date not null,
    close numeric not null,
    constraint marketprices_pkey primary key (id),
    constraint marketprices_ticker_date_key unique (ticker, date)
);

alter table public.market_prices enable row level security;
